CREATE TABLE INCIDENT (
    IncidentID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Title               VARCHAR2(150)       NOT NULL,
    Description         VARCHAR2(1000),
    StartTime           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    EndTime             TIMESTAMP,
    Severity            VARCHAR2(20)        NOT NULL,
    CONSTRAINT CHK_INCIDENT_SEVERITY CHECK (Severity IN ('Minor', 'Moderate', 'Major', 'Critical')),
    CONSTRAINT CHK_INCIDENT_TIMEFRAME CHECK (EndTime IS NULL OR EndTime >= StartTime)
);

CREATE TABLE AFFECTEDSEGMENT (
    AffectedSegmentID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IncidentID          NUMBER              NOT NULL,
    SegmentID           NUMBER              NOT NULL,
    StatusType          VARCHAR2(20)        NOT NULL,
    DelayMinutes        NUMBER(4)           DEFAULT 0 NOT NULL,
    CONSTRAINT FK_AFFSEG_INCIDENT FOREIGN KEY (IncidentID) REFERENCES INCIDENT(IncidentID) ON DELETE CASCADE,
    CONSTRAINT FK_AFFSEG_SEGMENT  FOREIGN KEY (SegmentID)  REFERENCES SEGMENT(SegmentID)   ON DELETE CASCADE,
    CONSTRAINT CHK_AFFSEG_STATUS  CHECK (StatusType IN ('Delayed', 'Suspended', 'Rerouted', 'Normal'))
);

CREATE TABLE AFFECTEDSTATION (
    AffectedStationID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IncidentID          NUMBER              NOT NULL,
    StationID           NUMBER              NOT NULL,
    StatusType          VARCHAR2(20)        NOT NULL,
    Reason              VARCHAR2(255),
    CONSTRAINT FK_AFFSTAT_INCIDENT FOREIGN KEY (IncidentID) REFERENCES INCIDENT(IncidentID) ON DELETE CASCADE,
    CONSTRAINT FK_AFFSTAT_STATION  FOREIGN KEY (StationID)  REFERENCES STATION(StationID)   ON DELETE CASCADE,
    CONSTRAINT CHK_AFFSTAT_STATUS  CHECK (StatusType IN ('Open', 'PartiallyClosed', 'Closed', 'Congested'))
);

