CREATE TABLE FARECLASS (
    FareClassID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name                VARCHAR2(60)        NOT NULL,
    DiscountPercentage  NUMBER(5,2)         DEFAULT 0.00 NOT NULL,
    RequiresVerification NUMBER(1)          DEFAULT 0 NOT NULL,
    IsActive            NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT CHK_FARECLASS_DISCOUNT CHECK (DiscountPercentage BETWEEN 0 AND 100),
    CONSTRAINT CHK_FARECLASS_VERIF    CHECK (RequiresVerification IN (0, 1)),
    CONSTRAINT CHK_FARECLASS_ACTIVE   CHECK (IsActive IN (0, 1))
);

CREATE TABLE SEGMENTFARE (
    SegmentFareID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SegmentID           NUMBER              NOT NULL,
    BaseAmount          NUMBER(8,2)         NOT NULL,
    ValidFrom           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    ValidTo             TIMESTAMP,
    IsActive            NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT FK_SEGFARE_SEGMENT   FOREIGN KEY (SegmentID) REFERENCES SEGMENT(SegmentID) ON DELETE CASCADE,
    CONSTRAINT CHK_SEGFARE_AMOUNT   CHECK (BaseAmount >= 0),
    CONSTRAINT CHK_SEGFARE_ACTIVE   CHECK (IsActive IN (0, 1)),
    CONSTRAINT CHK_SEGFARE_TIMEFRAME CHECK (ValidTo IS NULL OR ValidTo >= ValidFrom)
);

