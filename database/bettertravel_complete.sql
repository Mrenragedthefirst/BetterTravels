CREATE TABLE STATION_PAIR_TRANSFER (
    TransferID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FromStationID       NUMBER              NOT NULL,
    ToStationID         NUMBER              NOT NULL,
    WalkingDistance     NUMBER(6)           NOT NULL, -- meters
    WalkingTime         NUMBER(4)           NOT NULL, -- minutes
    IsDirectConnection  NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT FK_SPTRANSFER_FROMSTATION FOREIGN KEY (FromStationID) REFERENCES STATION(StationID) ON DELETE CASCADE,
    CONSTRAINT FK_SPTRANSFER_TOSTATION   FOREIGN KEY (ToStationID)   REFERENCES STATION(StationID) ON DELETE CASCADE,
    CONSTRAINT UQ_SPTRANSFER_PAIR        UNIQUE (FromStationID, ToStationID),
    CONSTRAINT CHK_SPTRANSFER_DIFF       CHECK (FromStationID <> ToStationID),
    CONSTRAINT CHK_SPTRANSFER_DIRECT     CHECK (IsDirectConnection IN (0, 1))
);

CREATE TABLE ROUTETRANSFER (
    RouteTransferID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FromRouteID         NUMBER              NOT NULL,
    ToRouteID           NUMBER              NOT NULL,
    CommonStationID     NUMBER              NOT NULL,
    TransferTime        NUMBER(4)           NOT NULL, -- minutes
    MinimumWaitTime     NUMBER(4)           DEFAULT 2 NOT NULL, -- minutes
    IsActive            NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT FK_RTRANSFER_FROMROUTE   FOREIGN KEY (FromRouteID)     REFERENCES ROUTE(RouteID)     ON DELETE CASCADE,
    CONSTRAINT FK_RTRANSFER_TOROUTE     FOREIGN KEY (ToRouteID)       REFERENCES ROUTE(RouteID)     ON DELETE CASCADE,
    CONSTRAINT FK_RTRANSFER_STATION     FOREIGN KEY (CommonStationID) REFERENCES STATION(StationID) ON DELETE CASCADE,
    CONSTRAINT UQ_RTRANSFER_CONFIG      UNIQUE (FromRouteID, ToRouteID, CommonStationID),
    CONSTRAINT CHK_RTRANSFER_DIFF       CHECK (FromRouteID <> ToRouteID),
    CONSTRAINT CHK_RTRANSFER_ACTIVE     CHECK (IsActive IN (0, 1))
);

