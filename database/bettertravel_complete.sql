CREATE TABLE JOURNEYLEG (
    JourneyLegID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SmartCardID         NUMBER              NOT NULL,
    PassengerID         NUMBER              NOT NULL,
    FromStationID       NUMBER              NOT NULL,
    ToStationID         NUMBER,
    TapInTime           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    TapOutTime          TIMESTAMP,
    FareDeducted        NUMBER(8,2)         DEFAULT 0.00 NOT NULL,
    FareClassAtTime     VARCHAR2(60)        NOT NULL,
    Status              VARCHAR2(20)        DEFAULT 'InProgress' NOT NULL,
    CONSTRAINT FK_JLEG_SMARTCARD FOREIGN KEY (SmartCardID)   REFERENCES SMARTCARD(SmartCardID) ON DELETE CASCADE,
    CONSTRAINT FK_JLEG_PASSENGER FOREIGN KEY (PassengerID)   REFERENCES PASSENGER(PassengerID) ON DELETE CASCADE,
    CONSTRAINT FK_JLEG_FROMSTAT  FOREIGN KEY (FromStationID) REFERENCES STATION(StationID),
    CONSTRAINT FK_JLEG_TOSTAT    FOREIGN KEY (ToStationID)   REFERENCES STATION(StationID),
    CONSTRAINT CHK_JLEG_STATUS   CHECK (Status IN ('InProgress', 'Completed', 'Cancelled', 'Incomplete'))
);

CREATE TABLE JOURNEYROUTE (
    JourneyRouteUsedID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
