CREATE TABLE STATION (
    StationID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name                VARCHAR2(100)       NOT NULL,
    City                VARCHAR2(60)        NOT NULL,
    Latitude            NUMBER(9,6)         NOT NULL,
    Longitude           NUMBER(9,6)         NOT NULL,
    Address             VARCHAR2(255),
    IsActive            NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT CHK_STATION_ACTIVE CHECK (IsActive IN (0, 1))
);

CREATE TABLE ROUTE (
    RouteID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name                VARCHAR2(100)       NOT NULL,
    "Mode"              VARCHAR2(20)        NOT NULL,
    Operator            VARCHAR2(100)       NOT NULL,
    IsActive            NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT CHK_ROUTE_MODE CHECK ("Mode" IN ('Metro', 'Bus', 'Train')),
    CONSTRAINT CHK_ROUTE_ACTIVE CHECK (IsActive IN (0, 1))
);

CREATE TABLE ROUTESTOP (
    RouteStopID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RouteID             NUMBER              NOT NULL,
    StationID           NUMBER              NOT NULL,
    Sequence            NUMBER(4)           NOT NULL,
    PlatformNumber      VARCHAR2(20),
    IsActive            NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT FK_ROUTESTOP_ROUTE   FOREIGN KEY (RouteID)   REFERENCES ROUTE(RouteID)     ON DELETE CASCADE,
    CONSTRAINT FK_ROUTESTOP_STATION FOREIGN KEY (StationID) REFERENCES STATION(StationID) ON DELETE CASCADE,
    CONSTRAINT UQ_ROUTE_SEQUENCE    UNIQUE (RouteID, Sequence),
    CONSTRAINT CHK_ROUTESTOP_ACTIVE CHECK (IsActive IN (0, 1))
);

CREATE TABLE SEGMENT (
    SegmentID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RouteID             NUMBER              NOT NULL,
    FromRouteStopID     NUMBER              NOT NULL,
    ToRouteStopID       NUMBER              NOT NULL,
    Distance            NUMBER(6,2)         NOT NULL, -- kilometers
    ScheduledTime       NUMBER(4)           NOT NULL, -- minutes
    IsActive            NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT FK_SEGMENT_ROUTE         FOREIGN KEY (RouteID)         REFERENCES ROUTE(RouteID)         ON DELETE CASCADE,
    CONSTRAINT FK_SEGMENT_FROMSTOP      FOREIGN KEY (FromRouteStopID) REFERENCES ROUTESTOP(RouteStopID) ON DELETE CASCADE,
    CONSTRAINT FK_SEGMENT_TOSTOP        FOREIGN KEY (ToRouteStopID)   REFERENCES ROUTESTOP(RouteStopID) ON DELETE CASCADE,
    CONSTRAINT UQ_SEGMENT_PAIR          UNIQUE (RouteID, FromRouteStopID, ToRouteStopID),
    CONSTRAINT CHK_SEGMENT_ACTIVE       CHECK (IsActive IN (0, 1)),
    CONSTRAINT CHK_SEGMENT_DISTANCE     CHECK (Distance > 0),
    CONSTRAINT CHK_SEGMENT_TIME         CHECK (ScheduledTime > 0)
);

